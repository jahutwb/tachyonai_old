# Helper functions
def get_last_completed_session(db: Session, user_id: int) -> Optional[SessionModel]:
    """
    Get the last completed session for a user.

    Args:
        db: Database session
        user_id: User ID

    Returns:
        Last completed session or None if there isn't any
    """
    return db.query(SessionModel).filter(
        SessionModel.user_id == user_id,
        SessionModel.status == schemas.SessionStatusEnum.COMPLETED
    ).order_by(SessionModel.ended_at.desc()).first()


