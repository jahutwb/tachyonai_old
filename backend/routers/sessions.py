@router.get("/sessions/{session_id}/pool-info", response_model=dict)
async def get_pool_info(
    session_id: int,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Check session status and return information about PENDING session and pool statistics.

    Args:
        session_id: ID of the session to check
        current_user: Current authenticated user
        db: Database session

    Returns:
        Dictionary containing information about the session and pool statistics

    Raises:
        HTTPException: If there's an error checking the pool status
    """
    try:
        # Check if a PENDING session exists
        pending_session = db.query(SessionModel).filter(
            SessionModel.user_id == current_user.id,
            SessionModel.status == schemas.SessionStatusEnum.PENDING
        ).order_by(SessionModel.id.desc()).first()

        if pending_session:
            logger.info(f"Found PENDING session {pending_session.id} for user {current_user.id}")

            # Check if the session has generated pools
            has_generated_pools = False
            pool_stats = None

            if pending_session.pos_pool_json and pending_session.neg_pool_json:
                try:
                    # Safely validate JSON fields
                    if isinstance(pending_session.pos_pool_json, list) and isinstance(pending_session.neg_pool_json, list):
                        has_generated_pools = True
                        logger.info(f"Session {pending_session.id} has generated pools")

                        # Calculate pool statistics
                        pool_stats = {
                            "pos_pool": {
                                "total": len(pending_session.pos_pool_json),
                                "bought": sum(1 for item in pending_session.pos_pool_json if item.get("origin", "random") == "bought"),
                                "children": sum(1 for item in pending_session.pos_pool_json if item.get("origin", "").startswith("child_of_")),
                                "random": sum(1 for item in pending_session.pos_pool_json if item.get("origin", "random") == "random"),
                                "random_fallback": sum(1 for item in pending_session.pos_pool_json if item.get("origin", "").startswith("random_fallback_for_")),
                                "images": [{
                                    "id": item["id"],
                                    "origin": item.get("origin", "random"),
                                    "successes": item.get("successes", 0),
                                    "failures": item.get("failures", 0)
                                } for item in pending_session.pos_pool_json]
                            },
                            "neg_pool": {
                                "total": len(pending_session.neg_pool_json),
                                "bought": sum(1 for item in pending_session.neg_pool_json if item.get("origin", "random") == "bought"),
                                "children": sum(1 for item in pending_session.neg_pool_json if item.get("origin", "").startswith("child_of_")),
                                "random": sum(1 for item in pending_session.neg_pool_json if item.get("origin", "random") == "random"),
                                "random_fallback": sum(1 for item in pending_session.neg_pool_json if item.get("origin", "").startswith("random_fallback_for_")),
                                "images": [{
                                    "id": item["id"],
                                    "origin": item.get("origin", "random"),
                                    "successes": item.get("successes", 0),
                                    "failures": item.get("failures", 0)
                                } for item in pending_session.neg_pool_json]
                            },
                            "total_images": len(pending_session.pos_pool_json) + len(pending_session.neg_pool_json)
                        }
                except Exception as e:
                    logger.error(f"Error checking JSON fields: {str(e)}")
                    has_generated_pools = False

            return {
                "has_pending_session": True,
                "pending_session_id": pending_session.id,
                "has_generated_pools": has_generated_pools,
                "pool_stats": pool_stats
            }
        else:
            return {
                "has_pending_session": False,
                "pending_session_id": None,
                "has_generated_pools": False,
                "pool_stats": None
            }

    except Exception as e:
        logger.error(f"Error checking pool status: {str(e)}")
        raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=str(e))


@router.post("/sessions/generate-pending", response_model=schemas.Message)
async def generate_pending_session(
    request: schemas.GenerateNewPoolRequest,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Generate a new session in PENDING state based on a previous session.

    Args:
        request: Request containing the previous session ID
        current_user: Current authenticated user
        db: Database session

    Returns:
        Message indicating the result of the operation

    Raises:
        HTTPException: If the previous session doesn't exist, isn't completed, or there's an error generating the new session
    """
    try:
        logger.info(f"Starting new pool generation for user {current_user.id}")

        previous_session = db.query(SessionModel).filter(
            SessionModel.id == request.previous_session_id,
            SessionModel.user_id == current_user.id
        ).first()

        if not previous_session:
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Previous session not found")

        if previous_session.status != schemas.SessionStatusEnum.COMPLETED:
            raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Previous session is not completed")

        try:
            pos_pool_json = previous_session.pos_pool_json or []
            neg_pool_json = previous_session.neg_pool_json or []

            logger.info(f"Successfully parsed positive pool JSON: {len(pos_pool_json)} items")
            logger.info(f"Successfully parsed negative pool JSON: {len(neg_pool_json)} items")
        except Exception as e:
            logger.error(f"Error parsing pool JSON: {str(e)}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Error parsing pool JSON")

        try:
            logger.info(f"Starting new pool generation based on session {previous_session.id}")

            new_pos_pool, new_neg_pool = generate_pool_with_genetic_algorithm(previous_session, db)

            # Ensure each item is an instance of PoolImageItem
            new_pos_pool_json = [
                item.to_dict() if isinstance(item, PoolImageItem) else PoolImageItem.from_dict(item).to_dict()
                for item in new_pos_pool
            ]
            new_neg_pool_json = [
                item.to_dict() if isinstance(item, PoolImageItem) else PoolImageItem.from_dict(item).to_dict()
                for item in new_neg_pool
            ]

            logger.info(f"Generated new pool: {len(new_pos_pool_json)} positive, {len(new_neg_pool_json)} negative")
        except Exception as e:
            logger.error(f"Error generating new pool: {str(e)}")
            logger.error(traceback.format_exc())
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Error generating new pool")

        new_session = SessionModel(
            user_id=current_user.id,
            status=schemas.SessionStatusEnum.PENDING,
            pos_pool_json=new_pos_pool_json,
            neg_pool_json=new_neg_pool_json,
            session_profit_factor=1.0,
            remaining_pairs=6
        )

        db.add(new_session)
        db.commit()
        db.refresh(new_session)

        logger.info(f"Created new PENDING session (id={new_session.id}) for user {current_user.id}")

        return schemas.Message(message="Created new PENDING session")

    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Error generating PENDING session: {str(e)}")
        logger.error(traceback.format_exc())
        raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=str(e))

@router.post("/sessions/{session_id}/trigger-pool-generation", response_model=schemas.Message)
async def trigger_pool_generation(
    session_id: int,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Trigger new pool generation for a user after clicking on session summary.

    Args:
        session_id: ID of the session to use as a base for generation
        current_user: Current authenticated user
        db: Database session

    Returns:
        Message indicating the result of the operation

    Raises:
        HTTPException: If the session doesn't exist or there's an error triggering pool generation
    """
    try:
        # Check if the session exists and belongs to the current user
        session = db.query(SessionModel).filter(
            SessionModel.id == session_id,
            SessionModel.user_id == current_user.id
        ).first()

        if not session:
            raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Session not found")

        # Check if a PENDING session already exists
        existing_pending = db.query(SessionModel).filter(
            SessionModel.user_id == current_user.id,
            SessionModel.status == schemas.SessionStatusEnum.PENDING
        ).first()

        if existing_pending:
            logger.info(f"PENDING session already exists (id={existing_pending.id}) for user {current_user.id}")
            return {"message": f"PENDING session already exists (id={existing_pending.id})"}

        # Use the existing generate_pending_session function
        # Prepare a request object as expected by generate_pending_session
        request = schemas.GenerateNewPoolRequest(previous_session_id=session_id)

        # Call the generate_pending_session function
        logger.info(f"Calling generate_pending_session for session {session_id}")
        result = await generate_pending_session(request, current_user, db)

        return {"message": "Started generating new pool"}

    except Exception as e:
        logger.error(f"Error triggering pool generation: {str(e)}")
        logger.error(traceback.format_exc())
        raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=str(e))

@router.get("/sessions/{session_id}/pools", response_model=List[Dict])
async def get_session_pools(
    session_id: int,
    type: schemas.ImageTypeEnum = Query(schemas.ImageTypeEnum.POSITIVE, description="Pool type: POSITIVE or NEGATIVE"),
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Get the pool of stimuli (positive/negative) for a given session.

    Args:
        session_id: ID of the session to get pools for
        type: Type of pool to retrieve (POSITIVE or NEGATIVE)
        current_user: Current authenticated user
        db: Database session

    Returns:
        List of pool items

    Raises:
        HTTPException: If the pool type is invalid, the session doesn't exist, or the user doesn't have access to it
    """
    # Type is already validated by FastAPI

    # Get the session
    session = db.query(SessionModel).filter(
        SessionModel.id == session_id,
        SessionModel.user_id == current_user.id
    ).first()

    if not session:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Session not found or access denied")

    # Select the appropriate pool
    pool_json = session.pos_pool_json if type == schemas.ImageTypeEnum.POSITIVE else session.neg_pool_json

    # If the pool is empty, return an empty list
    if not pool_json:
        return []

    # Return the pool data
    return pool_json
